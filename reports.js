export const getStats = () => {
  const total = reports.length
  const critical = reports.filter(r => r.severity === 'critical').length
  const today = reports.filter(r => r.timestamp > Date.now() - 24 * 60 * 60 * 1000).length
  const telegram = reports.filter(r => r.source === 'telegram').length
  const discord = reports.filter(r => r.source === 'discord').length
  const newReports = reports.filter(r => r.isNew).length
  return { total, critical, today, telegram, discord, newReports }
}

export const getSeverityColor = (severity) => {
  switch (severity) {
    case 'critical': return '#ff2d55'
    case 'high': return '#ff9500'
    case 'medium': return '#ffcc00'
    case 'low': return '#34c759'
    default: return '#8e8e93'
  }
}

export const getStatusLabel = (status) => {
  switch (status) {
    case 'verified': return '✓ VERIFICADO'
    case 'active': return '⚡ ACTIVO'
    case 'claimed': return '⚠ REIVINDICADO'
    case 'unverified': return '? NO VERIFICADO'
    default: return status.toUpperCase()
  }
}

export const formatCount = (n) => {
  if (!n) return null
  if (n >= 1000000) return (n / 1000000).toFixed(1) + 'M'
  if (n >= 1000) return (n / 1000).toFixed(0) + 'K'
  return n.toString()
}

export const timeAgo = (ts) => {
  const diff = Date.now() - ts
  const mins = Math.floor(diff / 60000)
  const hrs = Math.floor(diff / 3600000)
  const days = Math.floor(diff / 86400000)
  if (mins < 60) return `hace ${mins}m`
  if (hrs < 24) return `hace ${hrs}h`
  return `hace ${days}d`
}
